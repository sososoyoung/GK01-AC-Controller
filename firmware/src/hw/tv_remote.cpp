bool tv::sendXiaomi(const String& key) {
    for (const auto& b : buttons) {
        if (key != b.key) continue;
        // Copy only the chosen signal from flash, avoiding permanent RAM usage.
        uint16_t* timings = new (std::nothrow) uint16_t[b.length];
        if (!timings) return false;
        memcpy_P(timings, b.data, b.length * sizeof(uint16_t));
        ir.sendRaw(timings, b.length, 38000);
        delete[] timings;
        leds.flashRed(30);
        return true;
    }
    return false;
}
